#!/usr/bin/env node
// 从 src/data/courses.ts(客户端的球场数据)生成迁移里的球场种子 SQL。
//   node scripts/gen-courses-seed.cjs            → 打印种子块
//   node scripts/gen-courses-seed.cjs --write    → 替换迁移文件里 BEGIN/END 之间的内容
// tests/coursesSeed.test.cjs 会校验迁移里的种子和客户端数据一致,两边不能各改各的。
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');

const ROOT = path.join(__dirname, '..');
const MIGRATION = path.join(ROOT, 'supabase/migrations/20261017100200_courses_authoritative.sql');
const BEGIN = '-- BEGIN COURSES SEED (generated by scripts/gen-courses-seed.cjs — do not edit by hand)';
const END = '-- END COURSES SEED';

function loadCourses() {
  const src = fs.readFileSync(path.join(ROOT, 'src/data/courses.ts'), 'utf8');
  const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
  const m = { exports: {} };
  new Function('require', 'module', 'exports', js)(() => ({}), m, m.exports);
  return m.exports.COURSES;
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

function seedBlock(courses) {
  const rows = courses.map((c) => {
    const pars = c.holes.map((h) => h.par);
    return `  (${q(c.id)}, ${q(c.name)}, ${q(c.city)}, ${q(c.state)}, ${c.course_rating}, ${c.slope_rating}, ${c.total_par}, array[${pars.join(',')}])`;
  });
  return [
    BEGIN,
    'insert into public.courses (id, name, city, state, course_rating, slope_rating, total_par, holes_par) values',
    rows.join(',\n'),
    'on conflict (id) do update set',
    '  name = excluded.name, city = excluded.city, state = excluded.state,',
    '  course_rating = excluded.course_rating, slope_rating = excluded.slope_rating,',
    '  total_par = excluded.total_par, holes_par = excluded.holes_par;',
    END,
  ].join('\n');
}

function extractFromMigration(text) {
  const a = text.indexOf(BEGIN);
  const b = text.indexOf(END);
  if (a === -1 || b === -1) return null;
  return text.slice(a, b + END.length);
}

module.exports = { loadCourses, seedBlock, extractFromMigration, MIGRATION, BEGIN, END };

if (require.main === module) {
  const block = seedBlock(loadCourses());
  if (process.argv.includes('--write')) {
    const text = fs.readFileSync(MIGRATION, 'utf8');
    const old = extractFromMigration(text);
    if (!old) throw new Error('migration has no seed markers');
    fs.writeFileSync(MIGRATION, text.replace(old, () => block));
    console.log(`wrote ${loadCourses().length} courses into ${path.relative(ROOT, MIGRATION)}`);
  } else {
    console.log(block);
  }
}
